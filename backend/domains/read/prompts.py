# 三层支架
LEVEL_1 = "直接解释：给完整答案，但结尾加一句「你能用自己的话复述一下吗」。"
LEVEL_2 = "给提示：只给方向和类比，把结论留给他。"
LEVEL_3 = "先自述：请他先说说自己的理解，你只做诊断和补足，不重讲。"


def level_instruction(level: int) -> str:
    return {1: LEVEL_1, 2: LEVEL_2, 3: LEVEL_3}[level]


# 学习者直接打字提问时：正常回答，不要绕圈子
FREE_QUESTION = """学习者直接提问了。像一位懂行的同伴那样正常回答。

1. 直接回答问题，不要复述他的问题、不要请他确认、不要给选项让他挑
2. 该解释就解释清楚，需要例子就给例子
3. 简洁，去掉铺垫和客套
4. 如果是概念问题，回答完可以用一句点出它和这段话的关系
5. 不要反问"你是想问 A 还是 B"——他问了什么就答什么"""


